// Writes the synthetic dataset (format: docs/data-format.md).
//
//   npm run data:generate                         # as of today
//   npm run data:generate -- --as-of 2026-10-10   # pinned date, byte-identical output
//
// Output: data/everest — the mill from Nov 2022 (two warm-up months) to the as-of date at
// 10:30 IST, today's floor, and the confirmed order book for the next 90 days. Live activity
// after that comes from the event stream (backend/stream/live_stream.py), not from a dataset.
const fs = require('fs');
const path = require('path');
const { generate } = require('./generate');
const { verifyFloor, verifyMonths } = require('./verify');

const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i > -1 ? process.argv[i + 1] : fallback;
};
const asOfDate = arg('--as-of', new Date().toISOString().slice(0, 10));
const dir = path.join(__dirname, '..', '..', 'data', 'everest');

const { data, asOf } = generate({ asOfDate });
verifyFloor(data, 'everest');
verifyMonths(data, 'everest', asOf);

fs.mkdirSync(dir, { recursive: true });
for (const [model, rows] of Object.entries(data)) {
  // One row per line keeps git diffs readable.
  fs.writeFileSync(path.join(dir, `${model}.json`), `[\n${rows.map((r) => JSON.stringify(r)).join(',\n')}\n]\n`);
}
const table = ['| Model | Rows |', '|---|---|', ...Object.entries(data).map(([m, rows]) => `| ${m} | ${rows.length} |`)].join('\n');
fs.writeFileSync(
  path.join(dir, 'README.md'),
  `# everest — synthetic dataset (seed syn2)\n\nGenerated by \`backend/prisma/synthetic\`, as of ${asOf} (10:30 IST). ` +
    `The mill runs from 1 Nov 2022 (two warm-up months) so January 2023 opens with work in progress.\n\n${table}\n`,
);
console.log(`data/everest  as of ${asOf}\n${table}`);
