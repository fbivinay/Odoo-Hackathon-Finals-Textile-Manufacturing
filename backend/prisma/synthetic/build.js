// Writes the synthetic datasets (format: docs/data-format.md).
//
//   npm run data:generate                         # as of today
//   npm run data:generate -- --as-of 2026-10-10   # pinned date, byte-identical output
//
// Output:
//   data/everest       history 2023-01-01 → as-of 10:30 IST, today's floor, next-90-day order book
//   data/everest-live  the same, advanced through the scripted live events in live.js
const fs = require('fs');
const path = require('path');
const { generate } = require('./generate');
const { applyLiveEvents } = require('./live');

const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i > -1 ? process.argv[i + 1] : fallback;
};
const asOfDate = arg('--as-of', new Date().toISOString().slice(0, 10));
const root = path.join(__dirname, '..', '..', 'data');

function write(dir, data, readme) {
  fs.mkdirSync(dir, { recursive: true });
  for (const [model, rows] of Object.entries(data)) {
    // One row per line keeps git diffs readable.
    fs.writeFileSync(path.join(dir, `${model}.json`), `[\n${rows.map((r) => JSON.stringify(r)).join(',\n')}\n]\n`);
  }
  fs.writeFileSync(path.join(dir, 'README.md'), readme);
}

function summary(data) {
  const lines = ['| Model | Rows |', '|---|---|'];
  for (const [model, rows] of Object.entries(data)) lines.push(`| ${model} | ${rows.length} |`);
  return lines.join('\n');
}

const { data, asOf } = generate({ asOfDate });
write(
  path.join(root, 'everest'),
  data,
  `# everest — synthetic dataset (seed syn1)\n\nSynthetic, generated by \`backend/prisma/synthetic\`. As of ${asOf} (10:30 IST).\n` +
    `History from 2023-01-01, current floor state at the as-of moment, confirmed orders due over the next 90 days.\n\n${summary(data)}\n`,
);
console.log(`data/everest       as of ${asOf}`);
console.log(summary(data));

const live = applyLiveEvents(JSON.parse(JSON.stringify(data)), { asOf });
write(
  path.join(root, 'everest-live'),
  live.data,
  `# everest-live — synthetic live-demo scenario (seed syn1)\n\nStarts from \`data/everest\` (as of ${asOf}) and applies the scripted events below, in order.\n` +
    `Every event row is synthetic. Import this folder to show the floor a few hours later.\n\n## Event log\n\n| # | Time (UTC) | Event | Effect |\n|---|---|---|---|\n` +
    `${live.events.map((e, i) => `| ${i + 1} | ${e.at} | ${e.kind} | ${e.detail} |`).join('\n')}\n\n${summary(live.data)}\n`,
);
console.log(`\ndata/everest-live  ${live.events.length} events applied`);
for (const e of live.events) console.log(`  ${e.at}  ${e.kind.padEnd(18)} ${e.detail}`);
